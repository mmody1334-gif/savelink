#!/usr/bin/env pwsh
#Requires -Version 5.1
<#
.SYNOPSIS
  SaveLink installer: creates .dev.vars, deploys the Worker, pushes secrets and
  registers the Telegram webhook in one run.

.DESCRIPTION
  Run from anywhere:
      powershell -ExecutionPolicy Bypass -File .\scripts\install.ps1
  or with the token already in hand:
      .\scripts\install.ps1 -BotToken "123456:ABC..."

  Requirements: Node.js 20+, an internet connection, and a Cloudflare login
  (`npx wrangler login`) or CLOUDFLARE_API_TOKEN in the environment.

.PARAMETER BotToken
  Token from @BotFather. If omitted, the script asks for it.

.PARAMETER SkipTests
  Skip typecheck + unit tests before deploying.

.PARAMETER LocalOnly
  Stop after installing dependencies and writing .dev.vars (no deploy).

.PARAMETER DryRun
  Print the plan and check prerequisites without changing anything.
#>
[CmdletBinding()]
param(
  [string]$BotToken = '',
  [switch]$SkipTests,
  [switch]$LocalOnly,
  [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

function Step([string]$text) { Write-Host "`n=== $text ===" -ForegroundColor Cyan }
function Ok([string]$text) { Write-Host "  OK  $text" -ForegroundColor Green }
function Warn([string]$text) { Write-Host "  !!  $text" -ForegroundColor Yellow }
function Fail([string]$text) { Write-Host "  XX  $text" -ForegroundColor Red; exit 1 }

# Windows PowerShell 5.1 turns anything a native tool writes to stderr into a
# terminating NativeCommandError while $ErrorActionPreference is 'Stop' - and
# npm prints harmless warnings there. Run native commands under 'Continue' and
# judge them by $LASTEXITCODE instead.
function Invoke-Native([scriptblock]$Command) {
  $previous = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try {
    & $Command
  } finally {
    $ErrorActionPreference = $previous
  }
}

function New-Secret {
  $value = (Invoke-Native { & node -e "console.log(require('crypto').randomBytes(32).toString('hex'))" } | Out-String)
  if ($LASTEXITCODE -ne 0 -or -not $value) { Fail 'Could not generate a secret with node.' }
  return $value.Trim()
}

function Read-DotVars([string]$path) {
  $map = @{}
  if (-not (Test-Path $path)) { return $map }
  foreach ($line in Get-Content $path) {
    if ($line -match '^\s*#') { continue }
    if ($line -match '^\s*([A-Za-z0-9_]+)\s*=\s*(.*)\s*$') {
      $map[$matches[1]] = $matches[2].Trim().Trim('"').Trim("'")
    }
  }
  return $map
}

function Write-DotVars([string]$path, [hashtable]$values) {
  $order = @('BOT_TOKEN', 'WEBHOOK_SECRET', 'SIGNING_SECRET', 'PUBLIC_BASE_URL', 'ENGINE_ORDER', 'PROFILE_MAX_ITEMS', 'MAX_UPLOAD_MB', 'RATE_LIMIT_PER_MIN', 'BOT_LOCALE', 'YTDLP_ENDPOINT', 'YTDLP_TOKEN', 'COBALT_INSTANCES', 'COBALT_API_KEY', 'IG_COOKIE', 'FB_COOKIE', 'PINTEREST_COOKIE')
  $lines = New-Object System.Collections.Generic.List[string]
  $lines.Add('# Generated by scripts/install.ps1 - local only, never commit this file.')
  foreach ($key in $order) {
    if ($values.ContainsKey($key) -and $values[$key]) { $lines.Add("$key=$($values[$key])") }
  }
  foreach ($key in $values.Keys) {
    if ($order -notcontains $key -and $values[$key]) { $lines.Add("$key=$($values[$key])") }
  }
  $encoding = New-Object System.Text.UTF8Encoding($false)
  [IO.File]::WriteAllText($path, ($lines -join "`n") + "`n", $encoding)
}

# ---------------------------------------------------------------- prerequisites
Step '1/8 Prerequisites'
$nodeVersion = (Invoke-Native { & node -p "process.versions.node" 2>$null } | Out-String).Trim()
if ($LASTEXITCODE -ne 0 -or -not $nodeVersion) { Fail 'Node.js is not installed. Install Node 20+ from https://nodejs.org and reopen the terminal.' }
$nodeMajor = [int]($nodeVersion.Split('.')[0])
if ($nodeMajor -lt 20) { Fail "Node $nodeVersion is too old. Install Node 20 or newer." }
Ok "Node $nodeVersion"
Ok "npm $((Invoke-Native { & npm -v } | Out-String).Trim())"

if (-not (Test-Path (Join-Path $root 'wrangler.toml'))) { Fail 'wrangler.toml not found. Run this script from the savelink project.' }

$whoami = (Invoke-Native { & npx wrangler whoami } | Out-String)
if ($LASTEXITCODE -ne 0 -or $whoami -match 'not authenticated|You are not logged in') {
  Warn 'Wrangler is not logged in. Run: npx wrangler login'
  if (-not $DryRun) { Fail 'Cannot deploy without a Cloudflare login.' }
} else {
  $account = ($whoami -split "`n" | Where-Object { $_ -match 'Account Name' } | Select-Object -First 1)
  Ok 'Cloudflare login found'
}

if (-not $BotToken) {
  $BotToken = Read-Host 'Paste the bot token from @BotFather'
}
$BotToken = $BotToken.Trim()
if ($BotToken -notmatch '^\d{6,}:[A-Za-z0-9_-]{30,}$') {
  Fail 'That does not look like a BotFather token (expected 123456789:AA...).'
}
Ok 'Bot token format looks valid'

# ---------------------------------------------------------------- KV namespace
Step '2/8 Preparing the KV namespace (CACHE)'
$wranglerPath = Join-Path $root 'wrangler.toml'
$wranglerText = Get-Content $wranglerPath -Raw
$kvMatch = [regex]::Match($wranglerText, '(?s)\[\[kv_namespaces\]\][^\[]*?binding\s*=\s*"CACHE"[^\[]*?id\s*=\s*"([^"]*)"')
if (-not $kvMatch.Success) {
  Warn 'No CACHE binding in wrangler.toml - button state and rate limits fall back to memory.'
} else {
  $kvId = $kvMatch.Groups[1].Value
  $kvList = (Invoke-Native { & npx wrangler kv namespace list } | Out-String)
  $kvFound = $false
  if ($LASTEXITCODE -eq 0) {
    try { $kvFound = @($kvList | ConvertFrom-Json | Where-Object { $_.id -eq $kvId }).Count -gt 0 } catch { $kvFound = $false }
  }
  if ($kvFound) {
    Ok "KV namespace ready ($kvId)"
  } elseif ($DryRun) {
    Warn "Dry run: KV namespace $kvId is not in this account and would be created."
  } else {
    $created = (Invoke-Native { & npx wrangler kv namespace create CACHE } | Out-String)
    $newKvId = [regex]::Match($created, 'id\s*=\s*"([a-f0-9]{32})"').Groups[1].Value
    if (-not $newKvId) { Fail "Could not create the KV namespace. Output:`n$created" }
    $wranglerText = $wranglerText.Replace($kvId, $newKvId)
    [IO.File]::WriteAllText($wranglerPath, $wranglerText, (New-Object System.Text.UTF8Encoding($false)))
    Ok "KV namespace created and written to wrangler.toml ($newKvId)"
  }
}

# ---------------------------------------------------------------- config file
Step '3/8 Writing .dev.vars'
$dotVarsPath = Join-Path $root '.dev.vars'
$existing = Read-DotVars $dotVarsPath

$values = @{
  BOT_TOKEN       = $BotToken
  WEBHOOK_SECRET  = if ($existing['WEBHOOK_SECRET']) { $existing['WEBHOOK_SECRET'] } else { New-Secret }
  SIGNING_SECRET  = if ($existing['SIGNING_SECRET']) { $existing['SIGNING_SECRET'] } else { New-Secret }
  PUBLIC_BASE_URL = $existing['PUBLIC_BASE_URL']
}
foreach ($key in @('ENGINE_ORDER', 'PROFILE_MAX_ITEMS', 'MAX_UPLOAD_MB', 'RATE_LIMIT_PER_MIN', 'BOT_LOCALE', 'YTDLP_ENDPOINT', 'YTDLP_TOKEN', 'COBALT_INSTANCES', 'COBALT_API_KEY', 'IG_COOKIE', 'FB_COOKIE', 'PINTEREST_COOKIE')) {
  if ($existing[$key]) { $values[$key] = $existing[$key] }
}

if (Test-Path $dotVarsPath) {
  if (-not $DryRun) {
    Copy-Item $dotVarsPath "$dotVarsPath.bak" -Force
    Warn '.dev.vars existed; a backup was written to .dev.vars.bak'
  }
}

if ($DryRun) {
  Ok 'Dry run: .dev.vars not written'
} else {
  Write-DotVars $dotVarsPath $values
  Ok 'Secrets generated and saved to .dev.vars (git-ignored)'
}

# ---------------------------------------------------------------- dependencies
Step '4/8 Installing dependencies'
if ($DryRun) {
  Ok 'Dry run: skipping npm install'
} else {
  Invoke-Native { & npm install --no-fund --no-audit }
  if ($LASTEXITCODE -ne 0) { Fail 'npm install failed.' }
  Ok 'Dependencies installed'
}

# ---------------------------------------------------------------- checks
Step '5/8 Typecheck + tests'
if ($DryRun -or $SkipTests) {
  Ok 'Skipped'
} else {
  Invoke-Native { & npx tsc --noEmit }
  if ($LASTEXITCODE -ne 0) { Fail 'TypeScript reported errors.' }
  Invoke-Native { & npx vitest run }
  if ($LASTEXITCODE -ne 0) { Fail 'Unit tests failed.' }
  Ok 'Code is healthy'
}

if ($LocalOnly) {
  Step 'Done (local only)'
  Write-Host '  Start the bot locally with:  npm run dev' -ForegroundColor Green
  Write-Host '  Telegram needs a public URL for the webhook, so local mode is only'
  Write-Host '  useful with a tunnel (cloudflared tunnel --url http://localhost:8787).'
  exit 0
}

if ($DryRun) {
  Step 'Done (dry run)'
  Write-Host '  Next real run:  .\scripts\install.ps1 -BotToken "<token>"' -ForegroundColor Green
  exit 0
}

# ---------------------------------------------------------------- deploy
Step '6/8 Deploying to Cloudflare Workers'
$deployOutput = Invoke-Native { & npx wrangler deploy 2>&1 }
$deployText = ($deployOutput | Out-String)
Write-Host $deployText
if ($LASTEXITCODE -ne 0) { Fail 'wrangler deploy failed. Read the output above.' }

$urlMatch = [regex]::Match($deployText, 'https://[A-Za-z0-9._-]+\.workers\.dev')
if (-not $urlMatch.Success) {
  Warn 'Could not detect the workers.dev URL automatically.'
  $baseUrl = (Read-Host 'Paste the deployed URL (https://<worker>.<subdomain>.workers.dev)').Trim()
} else {
  $baseUrl = $urlMatch.Value
}
$baseUrl = $baseUrl.TrimEnd('/')
Ok "Worker URL: $baseUrl"

$values['PUBLIC_BASE_URL'] = $baseUrl
Write-DotVars $dotVarsPath $values

# ---------------------------------------------------------------- secrets
Step '7/8 Uploading secrets'
$secretFile = Join-Path ([IO.Path]::GetTempPath()) ("savelink-secrets-{0}.json" -f ([guid]::NewGuid().ToString('N')))
try {
  $payload = @{
    BOT_TOKEN       = $values['BOT_TOKEN']
    WEBHOOK_SECRET  = $values['WEBHOOK_SECRET']
    SIGNING_SECRET  = $values['SIGNING_SECRET']
    PUBLIC_BASE_URL = $baseUrl
  }
  if ($values['IG_COOKIE']) { $payload['IG_COOKIE'] = $values['IG_COOKIE'] }
  if ($values['FB_COOKIE']) { $payload['FB_COOKIE'] = $values['FB_COOKIE'] }
  if ($values['PINTEREST_COOKIE']) { $payload['PINTEREST_COOKIE'] = $values['PINTEREST_COOKIE'] }
  if ($values['YTDLP_ENDPOINT']) { $payload['YTDLP_ENDPOINT'] = $values['YTDLP_ENDPOINT'] }
  if ($values['YTDLP_TOKEN']) { $payload['YTDLP_TOKEN'] = $values['YTDLP_TOKEN'] }
  if ($values['COBALT_INSTANCES']) { $payload['COBALT_INSTANCES'] = $values['COBALT_INSTANCES'] }
  if ($values['COBALT_API_KEY']) { $payload['COBALT_API_KEY'] = $values['COBALT_API_KEY'] }

  $json = $payload | ConvertTo-Json -Compress
  [IO.File]::WriteAllText($secretFile, $json, (New-Object System.Text.UTF8Encoding($false)))
  Invoke-Native { & npx wrangler secret bulk $secretFile }
  if ($LASTEXITCODE -ne 0) { Fail 'Uploading secrets failed.' }
  Ok 'Secrets uploaded (values are never printed)'
} finally {
  if (Test-Path $secretFile) { Remove-Item $secretFile -Force }
}

# ---------------------------------------------------------------- webhook
Step '8/8 Registering the Telegram webhook'
Invoke-Native { & npm run tg:setup }
if ($LASTEXITCODE -ne 0) { Fail 'Webhook registration failed. Check .dev.vars and the deploy output.' }

$health = $null
try {
  $health = Invoke-RestMethod -Uri "$baseUrl/api/health" -TimeoutSec 20
} catch {
  Warn "Health check failed: $($_.Exception.Message)"
}

$botUsername = ''
try {
  $me = Invoke-RestMethod -Uri "https://api.telegram.org/bot$($values['BOT_TOKEN'])/getMe" -TimeoutSec 20
  if ($me.ok) { $botUsername = $me.result.username }
} catch {
  Warn 'Could not read the bot username from Telegram.'
}

Step 'Install complete'
if ($health) { Ok ("Health: bot={0}, store={1}, engines={2}" -f $health.bot, $health.store, ($health.engines -join ',')) }
if ($botUsername) {
  Write-Host "`n  Open the bot:  https://t.me/$botUsername  and press Start" -ForegroundColor Green
} else {
  Write-Host "`n  Open the bot link printed by tg:setup and press Start" -ForegroundColor Green
}
Write-Host "  Worker  : $baseUrl" -ForegroundColor Green
Write-Host "  Health  : $baseUrl/api/health" -ForegroundColor Green
Write-Host "`n  Optional next steps:" -ForegroundColor Cyan
Write-Host '   - HD Instagram avatar:     npx wrangler secret put IG_COOKIE'
Write-Host '   - Real MP3 everywhere:     deploy sidecar/ and set YTDLP_ENDPOINT'
Write-Host '   - Re-run webhook later:    npm run tg:setup'
exit 0
